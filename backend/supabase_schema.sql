-- ==========================================
-- CLUB TEAM MANAGEMENT
-- ==========================================

-- Create Club Members Table
CREATE TABLE club_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id BIGINT REFERENCES clubs(id) ON DELETE CASCADE,
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('editor', 'moderator')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(club_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_club_members_club_id ON club_members(club_id);

-- ==========================================
-- EVENT DISCUSSION / COMMENT THREADS
-- ==========================================

CREATE TABLE event_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT REFERENCES events(id) ON DELETE CASCADE NOT NULL,
  user_id UUID REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  content TEXT NOT NULL CHECK (char_length(content) > 0 AND char_length(content) <= 1000),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_event_comments_event_id ON event_comments(event_id);
CREATE INDEX IF NOT EXISTS idx_event_comments_user_id ON event_comments(user_id);

-- ==========================================
-- CLUB OWNER ANALYTICS
-- ==========================================

CREATE TABLE club_analytics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  club_id BIGINT REFERENCES clubs(id) ON DELETE CASCADE NOT NULL,
  view_date DATE NOT NULL DEFAULT CURRENT_DATE,
  page_views INTEGER DEFAULT 0,
  UNIQUE(club_id, view_date)
);

CREATE INDEX IF NOT EXISTS idx_club_analytics_club_id ON club_analytics(club_id);
CREATE INDEX IF NOT EXISTS idx_club_analytics_date ON club_analytics(view_date);
